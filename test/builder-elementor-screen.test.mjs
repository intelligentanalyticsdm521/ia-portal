const readSrc = (p) => readFileSync(path.join(SRC, p), "utf8");

/** Every source file under src/builder, as [relative path, text]. */
function builderFiles(dir = BUILDER) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const full = path.join(dir, name);
    if (statSync(full).isDirectory()) out.push(...builderFiles(full));
    else if (/\.(ts|tsx)$/.test(name)) out.push([path.relative(SRC, full).replace(/\\/g, "/"), readFileSync(full, "utf8")]);
  }
  return out;
}

/** Source with comments removed, so a comment that NAMES a deleted thing is not a hit. */
const code = (text) => text.replace(/\/\*[\s\S]*?\*\//g, "").replace(/(^|[^:])\/\/.*$/gm, "$1");

