/**
 * THE SCREEN LAW (D-172, 2026-09-19) — the builder's screen is a copy of
 * Elementor's editor, and what Elementor does not have is NOT on it.
 *
 * Brandon, 2026-09-19, after opening the preview and finding a pop-up list of
 * widgets behind the "+ Add" pill: *"I literally said add is just for flexbox
 * then templates. No widgets."* and *"I want an exact copy, as close as we can
 * make it, to Elementor's UI."*
 *
 * WHY THIS FILE EXISTS. The pop-up survived a rebuild that was told "put the
 * widgets on the left", because every check that rebuild had asserted that the
 * NEW thing was there and none asserted that the OLD thing was gone. This file
 * is the other half: each test says what must be ABSENT and what must be
 * PRESENT in its place. If a change makes one of these fail, the change is
 * wrong — do not edit this file to make it pass. Ask Brandon.
 *
 * The law, in five lines:
 *   1. Widgets are in the LEFT PANEL and nowhere else. No pop-up list, no
 *      gallery tab of widgets, no slash command, no "+" that lists widgets.
 *   2. Adding a container is Elementor's add area, IN the page: a round "+"
 *      (Add New Container) -> "Which layout would you like to use?" Flexbox |
 *      Grid -> "Select your structure"; a round folder (Add Template); and the
 *      words "Drag widget here".
 *   3. A container's handle is three things: add, drag, delete. Everything
 *      else is on right-click.
 *   4. An empty container shows a "+" in the middle. Pressing it selects the
 *      container; a widget pressed on the left then lands INSIDE it.
 *   5. The words are Elementor's: Container, Grid, Add New Container, Add
 *      Template, Drag widget here, Edit <Widget>, Content / Style / Advanced.
 */
import { test, describe } from "node:test";
import assert from "node:assert/strict";
import { existsSync, readFileSync, readdirSync, statSync } from "node:fs";
import path from "node:path";

import { addSection, emptyDocument, makeContainer, makeSection, resetIds } from "../src/builder/model.ts";
import { insertSpotFor } from "../src/builder/insertPosition.ts";
import { openGroups } from "../src/builder/widgetGroups.ts";

const SRC = path.join(process.cwd(), "src");
const BUILDER = path.join(SRC, "builder");
const readSrc = (p) => readFileSync(path.join(SRC, p), "utf8");

/** Every source file under src/builder, as [relative path, text]. */
function builderFiles(dir = BUILDER) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const full = path.join(dir, name);
    if (statSync(full).isDirectory()) out.push(...builderFiles(full));
    else if (/\.(ts|tsx)$/.test(name)) out.push([path.relative(SRC, full).replace(/\\/g, "/"), readFileSync(full, "utf8")]);
  }
  return out;
}

/** Source with comments removed, so a comment that NAMES a deleted thing is not a hit. */
const code = (text) => text.replace(/\/\*[\s\S]*?\*\//g, "").replace(/(^|[^:])\/\/.*$/gm, "$1");

describe("SCREEN LAW 1 — widgets are in the left panel and nowhere else", () => {
  test("the pop-up widget list is DELETED, not hidden", () => {
    assert.equal(existsSync(path.join(BUILDER, "WidgetPicker.tsx")), false,
      "src/builder/WidgetPicker.tsx is back. Elementor has no pop-up list of widgets; widgets live in the left panel only.");
    for (const [file, text] of builderFiles()) {
      const c = code(text);
      assert.ok(!/from\s+["']\.\.?\/(?:.*\/)?WidgetPicker["']/.test(c), `${file} imports a WidgetPicker`);
      assert.ok(!/<WidgetPicker\b/.test(c), `${file} renders a WidgetPicker`);
      assert.ok(!c.includes("data-picker-kind"), `${file} draws picker tiles (data-picker-kind)`);
      assert.ok(!c.includes("onOpenPicker"), `${file} still has a door to the pop-up (onOpenPicker)`);
    }
  });

  test("and the left panel IS there, with every group open", () => {
    const pane = readSrc("builder/WidgetPane.tsx");
    assert.ok(pane.includes('export const PANE_TITLE = "Widgets"'), "the left panel lost its title");
    assert.ok(pane.includes("data-widget-kind"), "the left panel draws no widget tiles");
    const groups = [{ group: "Layout", widgets: [] }, { group: "Basic", widgets: [] }, { group: "General", widgets: [] }];
    assert.deepEqual(openGroups(groups, ""), ["Layout", "Basic", "General"],
      "a panel that opens with its groups shut hides the widgets; the reference opens them");
  });

  test("the template library lists templates, not widgets a second time", () => {
    const gallery = code(readSrc("builder/SectionGallery.tsx"));
    assert.ok(!/["']widgets["']/.test(gallery), "SectionGallery has a Widgets tab again");
    assert.ok(!gallery.includes("onPlaceWidget"), "SectionGallery can place a widget again");
    assert.ok(gallery.includes('"sections"') && gallery.includes('"templates"'), "the library lost its own tabs");
  });

  test("there is no slash command", () => {
    const canvas = code(readSrc("builder/Canvas.tsx"));
    const shell = code(readSrc("builder/BuilderShell.tsx"));
    for (const [name, c] of [["Canvas.tsx", canvas], ["BuilderShell.tsx", shell]]) {
      assert.ok(!/\bonSlash\b|\bSlashState\b|\bslashCommit\b|\bwatchSlash\b/.test(c), `${name} still has the slash command`);
    }
  });
});

describe("SCREEN LAW 2 — adding a container is Elementor's add area, in the page", () => {
  const area = readSrc("builder/AddSection.tsx");
  const areaCode = code(area);

  test("the three views, in Elementor's words", () => {
    for (const words of [
      'title="Add New Container"', 'title="Add Template"', "Drag widget here",
      "Which layout would you like to use?", "Flexbox", "Grid", "Select your structure",
    ]) assert.ok(areaCode.includes(words), `the add area lost: ${words}`);
  });

  test("it is IN the page: not a dialog, not floating, and it lists no widgets", () => {
    assert.ok(!/role=["']dialog["']/.test(areaCode), "the add area became a dialog again");
    assert.ok(!/position:\s*["']fixed["']/.test(areaCode), "the add area floats over the page again");
    assert.ok(!/widgetLabel|panelGroups|WidgetDef/.test(areaCode), "the add area knows about widgets; it must not list any");
  });

  test("the canvas draws it: always at the bottom, and above a section on its handle's +", () => {
    const canvas = code(readSrc("builder/Canvas.tsx"));
    assert.ok((canvas.match(/<AddSection\b/g) || []).length >= 2, "the canvas needs the bottom add area AND the one a handle opens");
    assert.ok(canvas.includes("onAddBlank") && canvas.includes("onAddTemplate"), "the add area's two outcomes are not wired");
    assert.ok(canvas.includes("onDropOnAddArea"), '"Drag widget here" has to take a drop');
    assert.ok(!canvas.includes("bxc-addplus"), 'the "+ Add" pill is back');
  });

  test("the gap between two sections is a drop line and takes no click", () => {
    const bar = code(readSrc("builder/AddBar.tsx"));
    assert.ok(!/<button\b/.test(bar), "AddBar grew a button. The gap between containers shows nothing until something is dragged over it.");
    assert.ok(bar.includes("bxc-addbar-drop"), "AddBar lost its drop line");
  });
});

describe("SCREEN LAW 3 — a handle is add, drag, delete; the rest is right-click", () => {
  const canvas = readSrc("builder/Canvas.tsx");
  const c = code(canvas);

  test("the section handle has exactly Elementor's three", () => {
    const a = c.indexOf('className="bxc-toolbar"');
    assert.ok(a > -1, "no handle on a section");
    const block = c.slice(a, c.indexOf("ref={hostRef}", a));
    const titles = [...block.matchAll(/title=(?:"([^"]+)"|\{[^}]*"(Delete Container)"\})/g)].map((m) => m[1] || m[2]);
    assert.ok(block.includes('title="Add Container"'), "the handle lost its +");
    assert.ok(block.includes("Edit Container"), "the handle lost its grip");
    assert.ok(block.includes("Delete Container"), "the handle lost its x");
    assert.equal((block.match(/<button\b/g) || []).length, 2, `the handle is + and x as buttons and the grip between them; found ${titles.join(", ")}`);
  });

  test("a widget's handle carries no row of tools", () => {
    for (const gone of ["data-widget-hidden", "data-widget-locked", "data-widget-more", "bxc-addin"]) {
      assert.ok(!c.includes(gone), `${gone} is back on the page. Lock, hide, duplicate and the menu are on right-click.`);
    }
    const menu = readSrc("builder/builderMenu.ts");
    for (const action of ['"duplicate"', '"lock"', '"hide"', '"copy"', '"paste"']) {
      assert.ok(menu.includes(action), `right-click lost ${action}, and the handle no longer has it either`);
    }
  });
});

describe("SCREEN LAW 4 — select a container, press a widget, it lands inside", () => {
  test("insertSpotFor puts it INSIDE the selected container, at the end", () => {
    resetIds();
    const box = makeContainer(undefined, []);
    const sec = makeSection({ label: "Section" });
    sec.columns[0].widgets = [box];
    const doc = addSection(emptyDocument(), sec);
    const spot = insertSpotFor(doc, { kind: "widget", sectionId: sec.id, columnIndex: 0, widgetIndex: 0, id: box.id }, null);
    assert.equal(spot.hostId, box.id, "with a container selected the widget must land inside it, as in the reference");
    assert.equal(spot.index, 0);
  });

  test('an empty container shows only its "+"', () => {
    const c = code(readSrc("builder/Canvas.tsx"));
    assert.ok(c.includes("bxc-addhere"), 'an empty container lost its "+"');
    assert.ok(!readSrc("builder/render.ts").includes("Drag anything in here"), "the empty container is printing a sentence again; the reference shows a +");
  });
});

describe("SCREEN LAW 5 — the words are Elementor's", () => {
  test("a container is called Container (or Grid), in the panel on the right and in the structure window", () => {
    const inspector = code(readSrc("builder/Inspector.tsx"));
    const nav = code(readSrc("builder/navigatorModel.ts"));
    assert.ok(inspector.includes('d === "grid" ? "Grid" : "Container"'), "the settings panel names a container something else");
    assert.ok(nav.includes('dir === "grid" ? "Grid" : "Container"'), "the structure window names a container something else");
  });
});
