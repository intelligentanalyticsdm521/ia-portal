/**
 * scripts/gen-widget-settings-keys.mjs — THE MACHINE FILES, TURNED INTO A TEST
 * FIXTURE.
 *
 * B-168 §C.1 item 3. Ten agents are about to write emitters that hand settings
 * to the page engine. An emitted key the engine does not have is not an error
 * anywhere: the widget publishes, the setting is dropped, and the author's
 * change quietly does nothing on the live page. That is the
 * `reference_catch_swallow_report_success` shape, on a customer's website.
 *
 * So the LEGAL KEYS are taken from the machine files — the two catalogues
 * scraped out of a real Elementor install on 2026-09-17, free and Pro — and
 * every family test asserts that every key its emitter produces is one of them.
 *
 * ── HOW TO REGENERATE ─────────────────────────────────────────────────────
 *   node scripts/gen-widget-settings-keys.mjs
 *
 * It reads the two catalogues from the knowledge base, which is NOT in this
 * repo, and writes `test/fixtures/WIDGET_SETTINGS_KEYS.json`, which is. Pass a
 * different knowledge-base folder as the first argument if yours is elsewhere.
 * The fixture is committed on purpose: a test that needs a 9 MB file outside
 * the repo to run is a test that does not run on the build machine.
 *
 * ── WHAT IS IN IT ─────────────────────────────────────────────────────────
 * One entry per Elementor widget slug — the slug the offer file uses:
 *
 *   title        Elementor's own title, which is what the panel tile says and
 *                what `test/builder-offers.test.mjs` matches a tile against.
 *   pro          whether it needs the paid add-on.
 *   groups       Elementor's own categories for it.
 *   keys         every control key the widget accepts, sorted.
 *   responsive   the subset the catalogue marks `responsive: true`, for which
 *                the panel stores `<key>_tablet` / `<key>_mobile` twins.
 *
 * Nothing is invented and nothing is filtered: this is a copy of what the real
 * editor reported, which is the only reason it can settle an argument.
 *
 * ── WHICH FILE A WIDGET IS IN DOES NOT SAY WHETHER IT IS PAID ─────────────
 * Checked, not assumed (2026-09-19): BOTH catalogues were scraped from
 * installs that had Pro, so `elementor.json` carries Form, Posts and Price
 * Table too, and 136 of its 154 slugs also appear in `pro.json`. What DOES say
 * is Elementor's own category — a Pro widget carries `pro-elements` in its
 * `categories`, which is how the editor draws the PRO badge on the tile. So
 * `pro` is read from the category and never from the filename.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(HERE, "..");
const KB = process.argv[2] || "C:/dev/claude code/overnight-report";

const SOURCES = [
  "BUILDER_WIDGET_CATALOG_2026-09-17.elementor.json",
  "BUILDER_WIDGET_CATALOG_2026-09-17.pro.json",
];

/** Elementor's own group for a paid widget. See the header. */
const PRO_GROUP = "pro-elements";

const widgets = {};
const from = [];

for (const file of SOURCES) {
  const full = path.join(KB, file);
  if (!fs.existsSync(full)) {
    console.error(`MISSING: ${full}\nPass the knowledge-base folder as the first argument.`);
    process.exit(1);
  }
  from.push(file);
  const cat = JSON.parse(fs.readFileSync(full, "utf8"));
  for (const [slug, w] of Object.entries(cat.widgets || {})) {
    const controls = w.controls || {};
    const groups = Array.isArray(w.categories) ? w.categories : [];
    const prior = widgets[slug];
    /* UNION, not replace. A slug in both files gets every key either install
       reported, because a key present in one and missing from the other is a
       key we would otherwise call illegal and fail a correct emitter on. */
    const keys = [...new Set([...(prior?.keys || []), ...Object.keys(controls)])].sort();
    const responsive = [...new Set([
      ...(prior?.responsive || []),
      ...Object.keys(controls).filter((k) => controls[k] && controls[k].responsive === true),
    ])].sort();
    widgets[slug] = {
      title: String(prior?.title || w.title || slug),
      pro: Boolean(prior?.pro) || groups.includes(PRO_GROUP),
      groups: [...new Set([...(prior?.groups || []), ...groups])],
      keys,
      responsive,
    };
  }
}

const out = {
  _about: "Generated by scripts/gen-widget-settings-keys.mjs from the two 2026-09-17 "
    + "Elementor catalogues. Every settings key a family emitter produces must be in "
    + "the widget's `keys`. Do not hand-edit: regenerate.",
  _generated_from: from,
  _widget_count: Object.keys(widgets).length,
  widgets: Object.fromEntries(Object.keys(widgets).sort().map((k) => [k, widgets[k]])),
};

const dest = path.join(REPO, "test", "fixtures", "WIDGET_SETTINGS_KEYS.json");
/* Compact on purpose: it is generated, never hand-edited, and indenting a
   hundred and seventy widgets' control keys costs a third of a megabyte in
   every clone for whitespace nobody reads. */
fs.writeFileSync(dest, `${JSON.stringify(out)}\n`, "utf8");
console.log(`wrote ${dest} — ${out._widget_count} widgets`);
